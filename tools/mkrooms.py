#!/usr/bin/env python3
"""Convert gfx/rooms.txt into build/rooms.h (packed room layout table).

Each layout becomes 154 bytes (14x11): 0 floor, 1 rock, 2 pit, 3 enemy spawn.
Also checks that every door can reach every other door, so a layout can
never trap the player.
"""
import sys
from collections import deque

W, H = 14, 11
CODE = {'.': 0, 'r': 1, 'p': 2, 'e': 3}
DOOR_CELLS = [(6, 0), (7, 0), (6, 10), (7, 10), (0, 5), (13, 5)]
CLEAR = [(6, 0), (7, 0), (6, 1), (7, 1), (6, 9), (7, 9), (6, 10), (7, 10),
         (0, 5), (1, 5), (12, 5), (13, 5)]


def check(name, grid):
    for x, y in CLEAR:
        if grid[y][x] != 0:
            sys.exit(f"{name}: door approach ({x},{y}) must be floor")
    start = DOOR_CELLS[0]
    seen = {start}
    q = deque([start])
    while q:
        x, y = q.popleft()
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            nx, ny = x + dx, y + dy
            if 0 <= nx < W and 0 <= ny < H and (nx, ny) not in seen and grid[ny][nx] in (0, 3):
                seen.add((nx, ny))
                q.append((nx, ny))
    for d in DOOR_CELLS:
        if d not in seen:
            sys.exit(f"{name}: door cell {d} unreachable")
    spawns = sum(row.count(3) for row in grid)
    if not 2 <= spawns <= 6:
        sys.exit(f"{name}: needs 2-6 spawn points, has {spawns}")


def main(src, out):
    rooms = []
    lines = open(src).read().splitlines()
    i = 0
    while i < len(lines):
        line = lines[i].rstrip()
        i += 1
        if not line or line.startswith('#'):
            continue
        if line.startswith('=='):
            name = line[2:].strip()
            grid = []
            for r in lines[i:i + H]:
                r = r.rstrip()
                if len(r) != W:
                    sys.exit(f"{name}: row '{r}' has width {len(r)}, expected {W}")
                grid.append([CODE[c] for c in r])
            i += H
            check(name, grid)
            rooms.append((name, grid))
            continue
        sys.exit(f"unrecognised line {i}: {line}")

    with open(out, 'w') as f:
        f.write("/* Generated by tools/mkrooms.py from gfx/rooms.txt. Do not edit. */\n")
        f.write(f"#define NUM_LAYOUTS {len(rooms)}\n")
        f.write(f"static const unsigned char layouts[{len(rooms)}][{W * H}] = {{\n")
        for name, grid in rooms:
            flat = [v for row in grid for v in row]
            f.write(f"  /* {name} */ {{" + ",".join(map(str, flat)) + "},\n")
        f.write("};\n")
    print(f"rooms: {len(rooms)} layouts")


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
